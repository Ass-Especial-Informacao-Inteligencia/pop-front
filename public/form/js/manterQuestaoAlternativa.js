export function changeQuestionType(questionId) {
    const questionType = document.getElementById(`${questionId}-type`).value;
    const alternativesContainer = document.getElementById(
        `${questionId}-alternatives`
    );

    // Questões copiadas como "Resposta Curta" não renderizam o container de alternativas
    if (!alternativesContainer) {
        if (questionType === 'Resposta Curta') return;
        const cardBody = document.getElementById(questionId);
        if (!cardBody) return;
        const container = document.createElement('div');
        container.id = `${questionId}-alternatives`;
        container.className = 'form-group overflow-auto';
        cardBody.appendChild(container);
        bindAlternativeRemoveEvents();
        return changeQuestionType(questionId);
    }

    if (questionType === 'Resposta Curta') {
        alternativesContainer.classList.add('d-none');
    } else if (
        questionType === 'Multipla Escolha' ||
        questionType === 'Unica Escolha' ||
        questionType === 'Unica Escolha-Bairro' ||
        questionType === 'Unica Escolha-Ubs' ||
        questionType === 'Unica Escolha-Setor'
    ) {
        
      
        alternativesContainer.classList.remove('d-none');
        if (!alternativesContainer.querySelector('button.btn.btn-secondary')) {
            const addAlternativeButton = document.createElement('button');
            addAlternativeButton.type = 'button';
            addAlternativeButton.classList.add(
                'btn',
                'btn-secondary',
                'mt-2',
                'mb-2'
            );
            addAlternativeButton.innerText = 'Adicionar Alternativa';
            addAlternativeButton.onclick = () =>
                addAlternative(questionId, questionType);
            alternativesContainer.appendChild(addAlternativeButton);
        }
    }
}

export function addAlternative(questionId, questionType) {
    const alternativeId = `${questionId}-alt-${Date.now()}`;
    const alternativesContainer = document.getElementById(`${questionId}-alternatives`);
    const alternativeContainer = document.createElement('div');

    if (questionType !== 'Unica Escolha-Bairro' && questionType !== 'Unica Escolha-Ubs'  && questionType !== 'Unica Escolha-Setor') {
        alternativeContainer.classList.add('alternative-container', 'mb-2'); // Adicionando classe para espaçamento entre as alternativas

        alternativeContainer.innerHTML = `
            <div class="input-group">
            <input type="${
                questionType === 'Multipla Escolha' ? 'checkbox' : 'radio'
            }" name="${questionId}-alternatives" id="${alternativeId}" class="mr-2">
            <input type="text" class="form-control question-alternatives alternative-input" placeholder="Digite a alternativa">
            <div class="input-group-append">
                <button type="button" class="btn btn-danger btn-remove-alternative" data-alternative-id="${alternativeId}">X</button>
            </div>
            </div>
        `;
        alternativesContainer.appendChild(alternativeContainer);
    } else if (questionType === 'Unica Escolha-Bairro') {
        alternativesContainer.innerHTML = '';
        questionType = 'Unica Escolha'

        Object.entries(bairrosFerrazDeVasconcelos).forEach(([bairro, value], index) => {
            const alternativeId = `${questionId}-alt-${Date.now()}`;
            const alternativeContainer = document.createElement('div');
            alternativeContainer.classList.add('alternative-container', 'mb-2'); // Adicionando classe para espaçamento entre as alternativas
            alternativeContainer.innerHTML = `
                <div class="input-group">
                <input type="radio" name="${questionId}-alternatives" id="${alternativeId}" class="mr-2">
                <input type="text" class="form-control question-alternatives alternative-input" value="${bairro}">
                <div class="input-group-append">
                    <button type="button" class="btn btn-danger btn-remove-alternative" data-alternative-id="${alternativeId}">X</button>
                </div>
                </div>
            `;
            alternativesContainer.appendChild(alternativeContainer);
        });
    }else if (questionType === 'Unica Escolha-Ubs') {
        alternativesContainer.innerHTML = ''; // Limpa alternativas existentes
         questionType = 'Unica Escolha'
        Object.entries(ubsFerrazDeVasconcelos).forEach(([ubs, value], index) => {
            const alternativeId = `${questionId}-alt-${Date.now()}`;
            const alternativeContainer = document.createElement('div');
            alternativeContainer.classList.add('alternative-container', 'mb-2'); // Adicionando classe para espaçamento entre as alternativas
            alternativeContainer.innerHTML = `
                <div class="input-group">
                <input type="radio" name="${questionId}-alternatives" id="${alternativeId}" class="mr-2">
                <input type="text" class="form-control question-alternatives alternative-input" value="${ubs}">
                <div class="input-group-append">
                    <button type="button" class="btn btn-danger btn-remove-alternative" data-alternative-id="${alternativeId}">X</button>
                </div>
                </div>
            `;
            alternativesContainer.appendChild(alternativeContainer);
        });
    } else if (questionType === 'Unica Escolha-Setor') {
        alternativesContainer.innerHTML = ''; // Limpa alternativas existentes
        
        // Aqui você não deve alterar o questionType, pois ele precisa manter a referência a 'Unica Escolha-Setor'
        Object.entries(bairroComSetor).forEach(([setor, value], index) => {
            const alternativeId = `${questionId}-alt-${Date.now()}`;
            const alternativeContainer = document.createElement('div');
            alternativeContainer.classList.add('alternative-container', 'mb-2'); // Adicionando classe para espaçamento entre as alternativas
            alternativeContainer.innerHTML = `
                <div class="input-group">
                <input type="radio" name="${questionId}-alternatives" id="${alternativeId}" class="mr-2">
                <input type="text" class="form-control question-alternatives alternative-input" value="${setor}">
                <div class="input-group-append">
                    <button type="button" class="btn btn-danger btn-remove-alternative" data-alternative-id="${alternativeId}">X</button>
                </div>
                </div>
            `;
            alternativesContainer.appendChild(alternativeContainer);
        });
    }
}

export function removeAlternative(alternativeId) {
    const alternativeContainer =
        document.getElementById(alternativeId).parentNode;
    alternativeContainer.remove();
}

export function removeQuestion(questionId) {
    const questionElement = document.getElementById(questionId).parentElement;
    questionElement.remove();
}

function bindAlternativeRemoveEvents() {
    const container = document.getElementById('questions-container');
    if (!container || container.dataset.removeBound) return;
    container.dataset.removeBound = '1';
    container.addEventListener('click', (e) => {
        const btn = e.target.closest('.btn-remove-alternative');
        if (btn) removeAlternative(btn.dataset.alternativeId);
    });
}

