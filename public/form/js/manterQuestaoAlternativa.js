export function moveQuestion(questionId, direction) {
    const questionsContainer = document.getElementById('questions-container');
    const questionCard = document.getElementById(questionId).closest('.question-card');

    if (!questionCard) {
        return;
    }

    // Obter todas as perguntas no contêiner
    const questions = Array.from(questionsContainer.children);
    const currentPosition = questions.indexOf(questionCard);

    // Calcular nova posição
    const newPosition = direction === 'up' ? currentPosition - 1 : currentPosition + 1;

    // Verificar se a nova posição é válida
    if (newPosition < 0 || newPosition >= questions.length) {
        return;
    }

    // Reordenar as perguntas
    questions.splice(currentPosition, 1);
    questions.splice(newPosition, 0, questionCard);

    // Atualizar o contêiner com a nova ordem
    questionsContainer.innerHTML = '';
    questions.forEach(question => questionsContainer.appendChild(question));

    // Atualizar a posição dos dados no DOM
    questions.forEach((question, index) => {
        question.dataset.position = index;
    });
}

